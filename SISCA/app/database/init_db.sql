-- ═══════════════════════════════════════════════════════════
-- SISCA — DDL PostgreSQL · Script de creación de base de datos
-- Politécnico Internacional · Bogotá, Colombia
--
-- Portado de Oracle XE a PostgreSQL (2026-09-30) para poder
-- desplegar en Render, donde no hay Oracle en capa gratuita.
-- La versión Oracle de este archivo queda en el historial de git.
--
-- ── Base compartida ──────────────────────────────────────────
-- SISCA y SIIHAPI viven en la MISMA base de datos (Render solo
-- permite una Postgres gratuita por workspace), pero en esquemas
-- distintos: SIIHAPI usa `public` (tablas `usuarios`, `materias`,
-- `docentes_perfil`, ...) y SISCA usa `sisca`. Así no hay choque
-- de nombres — sin el esquema aparte quedarían `usuario` (SISCA)
-- junto a `usuarios` (SIIHAPI), dos tablas de usuarios en la misma
-- base, que es justo la confusión que hay que evitar hasta que la
-- Fase 3 unifique el modelo de verdad.
--
-- Ejecutar:  psql "$DATABASE_URL" -f app/database/init_db.sql
-- Es idempotente: se puede correr en cada despliegue sin romper
-- nada ni perder datos.
-- ═══════════════════════════════════════════════════════════

CREATE SCHEMA IF NOT EXISTS sisca;
SET search_path TO sisca, public;

-- ═══════════════════════════════════════════
-- MÓDULO 1 — SEGURIDAD Y USUARIOS
-- ═══════════════════════════════════════════
CREATE TABLE IF NOT EXISTS USUARIO (
  ID_USUARIO        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ESTADO            CHAR(1)      DEFAULT 'A' NOT NULL,
  NOMBRE            VARCHAR(100) NOT NULL,
  APELLIDO          VARCHAR(100) NOT NULL,
  CORREO            VARCHAR(120) NOT NULL,
  CONTRASENA        VARCHAR(255) NOT NULL,
  ROL               VARCHAR(20)  NOT NULL,
  ACEPTA_TERMINOS   CHAR(1)      DEFAULT 'N',
  FECHA_REGISTRO    TIMESTAMPTZ  DEFAULT NOW(),
  CONSTRAINT uq_usuario_correo UNIQUE (CORREO),
  CONSTRAINT ck_usuario_rol    CHECK (ROL IN ('ADMINISTRADOR','DOCENTE','ESTUDIANTE')),
  CONSTRAINT ck_usuario_estado CHECK (ESTADO IN ('A','I'))
);

CREATE TABLE IF NOT EXISTS ADMINISTRADOR (
  ID_ADMINISTRADOR INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO       INTEGER NOT NULL,
  NIVEL_ACCESO     VARCHAR(10) DEFAULT 'TOTAL',
  CONSTRAINT fk_admin_usuario FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS DOCENTE (
  ID_DOCENTE   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO   INTEGER NOT NULL,
  ESPECIALIDAD VARCHAR(100),
  TELEFONO     VARCHAR(20),
  CONSTRAINT fk_docente_usuario FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE IF NOT EXISTS ESTUDIANTE (
  ID_ESTUDIANTE     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO        INTEGER NOT NULL,
  SEMESTRE          SMALLINT,
  CODIGO_ESTUDIANTE INTEGER,
  CONSTRAINT fk_est_usuario FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
  CONSTRAINT uq_codigo_est  UNIQUE (CODIGO_ESTUDIANTE)
);

-- ═══════════════════════════════════════════
-- MÓDULO 2 — GESTIÓN ACADÉMICA
-- ═══════════════════════════════════════════
CREATE TABLE IF NOT EXISTS CARRERA (
  ID_CARRERA     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE_CARRERA VARCHAR(100) NOT NULL,
  FACULTAD       VARCHAR(100),
  CODIGO_CARRERA VARCHAR(20),
  ESTADO         CHAR(1) DEFAULT 'A',
  CONSTRAINT uq_carrera_codigo UNIQUE (CODIGO_CARRERA)
);

CREATE TABLE IF NOT EXISTS MATERIA (
  ID_MATERIA     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_CARRERA     INTEGER,
  ID_DOCENTE     INTEGER,
  NOMBRE_MATERIA VARCHAR(150) NOT NULL,
  CODIGO         VARCHAR(20),
  CREDITOS       SMALLINT,
  SEMESTRE       SMALLINT,
  PORCENTAJE_MIN NUMERIC(5,2) DEFAULT 75.00,
  ESTADO         CHAR(1) DEFAULT 'A',
  CONSTRAINT fk_materia_carrera FOREIGN KEY (ID_CARRERA) REFERENCES CARRERA(ID_CARRERA),
  CONSTRAINT fk_materia_docente FOREIGN KEY (ID_DOCENTE) REFERENCES DOCENTE(ID_DOCENTE),
  CONSTRAINT uq_materia_codigo  UNIQUE (CODIGO)
);

CREATE TABLE IF NOT EXISTS HORARIO (
  ID_HORARIO  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_MATERIA  INTEGER NOT NULL,
  HORA_INICIO TIMESTAMPTZ NOT NULL,
  HORA_FIN    TIMESTAMPTZ NOT NULL,
  DIA         VARCHAR(20) NOT NULL,
  AULA        VARCHAR(30),
  ESTADO      CHAR(1) DEFAULT 'A',
  CONSTRAINT fk_horario_materia FOREIGN KEY (ID_MATERIA) REFERENCES MATERIA(ID_MATERIA)
);

CREATE TABLE IF NOT EXISTS INSCRIPCION (
  ID_INSCRIPCION    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ESTUDIANTE     INTEGER NOT NULL,
  ID_MATERIA        INTEGER NOT NULL,
  FECHA_INSCRIPCION DATE DEFAULT CURRENT_DATE,
  SEMESTRE          SMALLINT,
  ESTADO            VARCHAR(20) DEFAULT 'ACTIVA',
  CONSTRAINT fk_insc_est    FOREIGN KEY (ID_ESTUDIANTE) REFERENCES ESTUDIANTE(ID_ESTUDIANTE),
  CONSTRAINT fk_insc_mat    FOREIGN KEY (ID_MATERIA)    REFERENCES MATERIA(ID_MATERIA),
  CONSTRAINT ck_insc_estado CHECK (ESTADO IN ('ACTIVA','CANCELADA','COMPLETADA'))
);

-- ═══════════════════════════════════════════
-- MÓDULO 3 — CONTROL DE ASISTENCIA
-- ═══════════════════════════════════════════
CREATE TABLE IF NOT EXISTS SESION_CLASE (
  ID_SESION     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_HORARIO    INTEGER NOT NULL,
  FECHA_SESION  DATE DEFAULT CURRENT_DATE,
  ESTADO_SESION VARCHAR(30) DEFAULT 'ACTIVA',
  MODO_CONEXION VARCHAR(20) DEFAULT 'ONLINE',
  CONSTRAINT fk_sesion_horario FOREIGN KEY (ID_HORARIO) REFERENCES HORARIO(ID_HORARIO),
  CONSTRAINT ck_sesion_estado  CHECK (ESTADO_SESION IN ('ACTIVA','CERRADA','CANCELADA')),
  CONSTRAINT ck_sesion_modo    CHECK (MODO_CONEXION IN ('ONLINE','OFFLINE'))
);

CREATE TABLE IF NOT EXISTS CODIGO_QR (
  ID_QR            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SESION        INTEGER NOT NULL,
  FECHA_GENERACION TIMESTAMPTZ DEFAULT NOW(),
  FECHA_EXPIRACION TIMESTAMPTZ NOT NULL,
  CODIGO           VARCHAR(250) NOT NULL,
  IP_LOCAL         VARCHAR(50),
  USADO            CHAR(1) DEFAULT 'N',
  CONSTRAINT fk_qr_sesion FOREIGN KEY (ID_SESION) REFERENCES SESION_CLASE(ID_SESION),
  CONSTRAINT uq_qr_codigo UNIQUE (CODIGO)
);

CREATE TABLE IF NOT EXISTS ASISTENCIA (
  ID_ASISTENCIA  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SESION      INTEGER NOT NULL,
  ID_ESTUDIANTE  INTEGER NOT NULL,
  FECHA          DATE        DEFAULT CURRENT_DATE,
  HORA_REGISTRO  TIMESTAMPTZ DEFAULT NOW(),
  ESTADO         VARCHAR(20) DEFAULT 'PRESENTE',
  TIPO_REGISTRO  VARCHAR(20) DEFAULT 'QR',
  ID_DISPOSITIVO VARCHAR(100),
  LATITUD        NUMERIC(10,7),
  LONGITUD       NUMERIC(10,7),
  CONSTRAINT fk_asist_sesion FOREIGN KEY (ID_SESION)    REFERENCES SESION_CLASE(ID_SESION),
  CONSTRAINT fk_asist_est    FOREIGN KEY (ID_ESTUDIANTE) REFERENCES ESTUDIANTE(ID_ESTUDIANTE),
  CONSTRAINT uq_asistencia   UNIQUE (ID_SESION, ID_ESTUDIANTE),
  CONSTRAINT ck_asist_estado CHECK (ESTADO IN ('PRESENTE','AUSENTE','JUSTIFICADO')),
  CONSTRAINT ck_asist_tipo   CHECK (TIPO_REGISTRO IN ('QR','MANUAL','ENLACE','OFFLINE'))
);

CREATE TABLE IF NOT EXISTS JUSTIFICACION (
  ID_JUSTIFICACION INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ASISTENCIA    INTEGER,
  ID_DOCENTE       INTEGER,
  MOTIVO           VARCHAR(500),
  FECHA_REGISTRO   TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT fk_just_asist   FOREIGN KEY (ID_ASISTENCIA) REFERENCES ASISTENCIA(ID_ASISTENCIA),
  CONSTRAINT fk_just_docente FOREIGN KEY (ID_DOCENTE)    REFERENCES DOCENTE(ID_DOCENTE)
);

CREATE TABLE IF NOT EXISTS AUDITORIA (
  ID_LOG         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO     INTEGER,
  FECHA          TIMESTAMPTZ DEFAULT NOW(),
  ACCION         VARCHAR(150) NOT NULL,
  TABLA_AFECTADA VARCHAR(50),
  IP             VARCHAR(50),
  CONSTRAINT fk_audit_usuario FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

-- ═══════════════════════════════════════════
-- MÓDULO 4 — SINCRONIZACIÓN OFFLINE
-- ═══════════════════════════════════════════
CREATE TABLE IF NOT EXISTS SERVIDOR_LOCAL (
  ID_SERVIDOR_LOCAL INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  IP_LOCAL          VARCHAR(50),
  ESTADO_SERVIDOR   VARCHAR(20) DEFAULT 'ACTIVO',
  CONSTRAINT ck_svr_estado CHECK (ESTADO_SERVIDOR IN ('ACTIVO','INACTIVO','OFFLINE'))
);

CREATE TABLE IF NOT EXISTS SINCRONIZACION (
  ID_SINCRONIZACION    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SERVIDOR          INTEGER,
  FECHA_SINCRONIZACION TIMESTAMPTZ DEFAULT NOW(),
  ESTADO_CONEXION      VARCHAR(30),
  REGISTROS_SYNC       INTEGER DEFAULT 0,
  CONSTRAINT fk_sinc_servidor FOREIGN KEY (ID_SERVIDOR) REFERENCES SERVIDOR_LOCAL(ID_SERVIDOR_LOCAL)
);

CREATE TABLE IF NOT EXISTS ALERTA_INASISTENCIA (
  ID_ALERTA         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ESTUDIANTE     INTEGER,
  ID_MATERIA        INTEGER,
  PORCENTAJE_ACTUAL NUMERIC(5,2),
  NOTIFICADO        CHAR(1) DEFAULT 'N',
  FECHA_ALERTA      TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT fk_alerta_est FOREIGN KEY (ID_ESTUDIANTE) REFERENCES ESTUDIANTE(ID_ESTUDIANTE),
  CONSTRAINT fk_alerta_mat FOREIGN KEY (ID_MATERIA)    REFERENCES MATERIA(ID_MATERIA)
);

-- ═══════════════════════════════════════════
-- MÓDULO 5 — ENTRADA DESDE INTEGRA-PI (SSO)
-- ═══════════════════════════════════════════
-- Tickets de entrada ya canjeados. SIIHAPI firma un ticket de 60 segundos
-- cuando el usuario entra a Asistencia desde el portal; acá se guarda su
-- jti para que no se pueda canjear dos veces (la URL queda en el historial
-- del navegador y en los logs del proxy, así que reusarla es fácil).
-- La PK hace el trabajo: el segundo INSERT del mismo jti falla.
CREATE TABLE IF NOT EXISTS SSO_TICKET_USADO (
  JTI        VARCHAR(64) PRIMARY KEY,
  FECHA_USO  TIMESTAMPTZ DEFAULT NOW()
);

-- Los tickets viven 60 segundos: pasada esa ventana la fila ya no sirve
-- de nada. Este índice es para poder barrer las viejas sin escanear todo.
CREATE INDEX IF NOT EXISTS IDX_SSO_TICKET_FECHA ON SSO_TICKET_USADO(FECHA_USO);

-- ═══════════════════════════════════════════
-- ÍNDICES DE RENDIMIENTO (RNF-32)
-- ═══════════════════════════════════════════
CREATE INDEX IF NOT EXISTS IDX_ASIST_ESTUDIANTE ON ASISTENCIA(ID_ESTUDIANTE);
CREATE INDEX IF NOT EXISTS IDX_ASIST_SESION     ON ASISTENCIA(ID_SESION);
CREATE INDEX IF NOT EXISTS IDX_ASIST_FECHA      ON ASISTENCIA(FECHA);
CREATE INDEX IF NOT EXISTS IDX_LOG_FECHA        ON AUDITORIA(FECHA);
CREATE INDEX IF NOT EXISTS IDX_QR_CODIGO        ON CODIGO_QR(CODIGO);
CREATE INDEX IF NOT EXISTS IDX_SESION_HORARIO   ON SESION_CLASE(ID_HORARIO);
CREATE INDEX IF NOT EXISTS IDX_MATERIA_CARRERA  ON MATERIA(ID_CARRERA);
CREATE INDEX IF NOT EXISTS IDX_USUARIO_CORREO   ON USUARIO(CORREO);

