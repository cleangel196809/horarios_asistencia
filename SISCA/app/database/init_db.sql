-- ═══════════════════════════════════════════
-- MÓDULO 1 — SEGURIDAD Y USUARIOS
-- ═══════════════════════════════════════════
CREATE TABLE USUARIO (
  ID_USUARIO        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ESTADO            CHAR(1)       DEFAULT 'A' NOT NULL,
  NOMBRE            VARCHAR2(100) NOT NULL,
  APELLIDO          VARCHAR2(100) NOT NULL,
  CORREO            VARCHAR2(120) NOT NULL,
  CONTRASENA        VARCHAR2(255) NOT NULL,
  ROL               VARCHAR2(20)  NOT NULL,
  ACEPTA_TERMINOS   CHAR(1)       DEFAULT 'N',
  FECHA_REGISTRO    TIMESTAMP     DEFAULT SYSTIMESTAMP,
  CONSTRAINT uq_usuario_correo UNIQUE (CORREO),
  CONSTRAINT ck_usuario_rol    CHECK (ROL IN ('ADMINISTRADOR','DOCENTE','ESTUDIANTE')),
  CONSTRAINT ck_usuario_estado CHECK (ESTADO IN ('A','I'))
);

CREATE TABLE ADMINISTRADOR (
  ID_ADMINISTRADOR NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO       NUMBER NOT NULL,
  NIVEL_ACCESO     VARCHAR2(10) DEFAULT 'TOTAL',
  CONSTRAINT fk_admin_usuario FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE DOCENTE (
  ID_DOCENTE   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO   NUMBER NOT NULL,
  ESPECIALIDAD VARCHAR2(100),
  TELEFONO     VARCHAR2(20),
  CONSTRAINT fk_docente_usuario FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE ESTUDIANTE (
  ID_ESTUDIANTE     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO        NUMBER NOT NULL,
  SEMESTRE          NUMBER(2),
  CODIGO_ESTUDIANTE NUMBER,
  CONSTRAINT fk_est_usuario   FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
  CONSTRAINT uq_codigo_est    UNIQUE (CODIGO_ESTUDIANTE)
);

-- ═══════════════════════════════════════════
-- MÓDULO 2 — GESTIÓN ACADÉMICA
-- ═══════════════════════════════════════════
CREATE TABLE CARRERA (
  ID_CARRERA     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE_CARRERA VARCHAR2(100) NOT NULL,
  FACULTAD       VARCHAR2(100),
  CODIGO_CARRERA VARCHAR2(20),
  ESTADO         CHAR(1) DEFAULT 'A',
  CONSTRAINT uq_carrera_codigo UNIQUE (CODIGO_CARRERA)
);

CREATE TABLE MATERIA (
  ID_MATERIA     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_CARRERA     NUMBER,
  ID_DOCENTE     NUMBER,
  NOMBRE_MATERIA VARCHAR2(150) NOT NULL,
  CODIGO         VARCHAR2(20),
  CREDITOS       NUMBER(2),
  SEMESTRE       NUMBER(2),
  PORCENTAJE_MIN NUMBER(5,2) DEFAULT 75.00,
  ESTADO         CHAR(1) DEFAULT 'A',
  CONSTRAINT fk_materia_carrera FOREIGN KEY (ID_CARRERA) REFERENCES CARRERA(ID_CARRERA),
  CONSTRAINT fk_materia_docente FOREIGN KEY (ID_DOCENTE) REFERENCES DOCENTE(ID_DOCENTE),
  CONSTRAINT uq_materia_codigo  UNIQUE (CODIGO)
);

CREATE TABLE HORARIO (
  ID_HORARIO  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_MATERIA  NUMBER NOT NULL,
  HORA_INICIO TIMESTAMP NOT NULL,
  HORA_FIN    TIMESTAMP NOT NULL,
  DIA         VARCHAR2(20) NOT NULL,
  AULA        VARCHAR2(30),
  ESTADO      CHAR(1) DEFAULT 'A',
  CONSTRAINT fk_horario_materia FOREIGN KEY (ID_MATERIA) REFERENCES MATERIA(ID_MATERIA)
);

CREATE TABLE INSCRIPCION (
  ID_INSCRIPCION    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ESTUDIANTE     NUMBER NOT NULL,
  ID_MATERIA        NUMBER NOT NULL,
  FECHA_INSCRIPCION DATE DEFAULT SYSDATE,
  SEMESTRE          NUMBER(2),
  ESTADO            VARCHAR2(20) DEFAULT 'ACTIVA',
  CONSTRAINT fk_insc_est    FOREIGN KEY (ID_ESTUDIANTE) REFERENCES ESTUDIANTE(ID_ESTUDIANTE),
  CONSTRAINT fk_insc_mat    FOREIGN KEY (ID_MATERIA)    REFERENCES MATERIA(ID_MATERIA),
  CONSTRAINT ck_insc_estado CHECK (ESTADO IN ('ACTIVA','CANCELADA','COMPLETADA'))
);

-- ═══════════════════════════════════════════
-- MÓDULO 3 — CONTROL DE ASISTENCIA
-- ═══════════════════════════════════════════
CREATE TABLE SESION_CLASE (
  ID_SESION     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_HORARIO    NUMBER NOT NULL,
  FECHA_SESION  DATE DEFAULT SYSDATE,
  ESTADO_SESION VARCHAR2(30) DEFAULT 'ACTIVA',
  MODO_CONEXION VARCHAR2(20) DEFAULT 'ONLINE',
  CONSTRAINT fk_sesion_horario FOREIGN KEY (ID_HORARIO)  REFERENCES HORARIO(ID_HORARIO),
  CONSTRAINT ck_sesion_estado  CHECK (ESTADO_SESION IN ('ACTIVA','CERRADA','CANCELADA')),
  CONSTRAINT ck_sesion_modo    CHECK (MODO_CONEXION IN ('ONLINE','OFFLINE'))
);

CREATE TABLE CODIGO_QR (
  ID_QR             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SESION         NUMBER NOT NULL,
  FECHA_GENERACION  TIMESTAMP DEFAULT SYSTIMESTAMP,
  FECHA_EXPIRACION  TIMESTAMP NOT NULL,
  CODIGO            VARCHAR2(250) NOT NULL,
  IP_LOCAL          VARCHAR2(50),
  USADO             CHAR(1) DEFAULT 'N',
  CONSTRAINT fk_qr_sesion   FOREIGN KEY (ID_SESION) REFERENCES SESION_CLASE(ID_SESION),
  CONSTRAINT uq_qr_codigo   UNIQUE (CODIGO)
);

CREATE TABLE ASISTENCIA (
  ID_ASISTENCIA  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SESION      NUMBER NOT NULL,
  ID_ESTUDIANTE  NUMBER NOT NULL,
  FECHA          DATE DEFAULT SYSDATE,
  HORA_REGISTRO  TIMESTAMP DEFAULT SYSTIMESTAMP,
  ESTADO         VARCHAR2(20) DEFAULT 'PRESENTE',
  TIPO_REGISTRO  VARCHAR2(20) DEFAULT 'QR',
  ID_DISPOSITIVO VARCHAR2(100),
  LATITUD        NUMBER(10,7),
  LONGITUD       NUMBER(10,7),
  CONSTRAINT fk_asist_sesion  FOREIGN KEY (ID_SESION)     REFERENCES SESION_CLASE(ID_SESION),
  CONSTRAINT fk_asist_est     FOREIGN KEY (ID_ESTUDIANTE)  REFERENCES ESTUDIANTE(ID_ESTUDIANTE),
  CONSTRAINT uq_asistencia    UNIQUE (ID_SESION, ID_ESTUDIANTE),
  CONSTRAINT ck_asist_estado  CHECK (ESTADO IN ('PRESENTE','AUSENTE','JUSTIFICADO')),
  CONSTRAINT ck_asist_tipo    CHECK (TIPO_REGISTRO IN ('QR','MANUAL','ENLACE','OFFLINE'))
);

CREATE TABLE JUSTIFICACION (
  ID_JUSTIFICACION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ASISTENCIA    NUMBER,
  ID_DOCENTE       NUMBER,
  MOTIVO           VARCHAR2(500),
  FECHA_REGISTRO   TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_just_asist   FOREIGN KEY (ID_ASISTENCIA) REFERENCES ASISTENCIA(ID_ASISTENCIA),
  CONSTRAINT fk_just_docente FOREIGN KEY (ID_DOCENTE)    REFERENCES DOCENTE(ID_DOCENTE)
);

CREATE TABLE AUDITORIA (
  ID_LOG         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO     NUMBER,
  FECHA          TIMESTAMP DEFAULT SYSTIMESTAMP,
  ACCION         VARCHAR2(150) NOT NULL,
  TABLA_AFECTADA VARCHAR2(50),
  IP             VARCHAR2(50),
  CONSTRAINT fk_audit_usuario FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

-- ═══════════════════════════════════════════
-- MÓDULO 4 — SINCRONIZACIÓN OFFLINE
-- ═══════════════════════════════════════════
CREATE TABLE SERVIDOR_LOCAL (
  ID_SERVIDOR_LOCAL NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  IP_LOCAL          VARCHAR2(50),
  ESTADO_SERVIDOR   VARCHAR2(20) DEFAULT 'ACTIVO',
  CONSTRAINT ck_svr_estado CHECK (ESTADO_SERVIDOR IN ('ACTIVO','INACTIVO','OFFLINE'))
);

CREATE TABLE SINCRONIZACION (
  ID_SINCRONIZACION    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_SERVIDOR          NUMBER,
  FECHA_SINCRONIZACION TIMESTAMP DEFAULT SYSTIMESTAMP,
  ESTADO_CONEXION      VARCHAR2(30),
  REGISTROS_SYNC       NUMBER DEFAULT 0,
  CONSTRAINT fk_sinc_servidor FOREIGN KEY (ID_SERVIDOR) REFERENCES SERVIDOR_LOCAL(ID_SERVIDOR_LOCAL)
);

CREATE TABLE ALERTA_INASISTENCIA (
  ID_ALERTA         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_ESTUDIANTE     NUMBER,
  ID_MATERIA        NUMBER,
  PORCENTAJE_ACTUAL NUMBER(5,2),
  NOTIFICADO        CHAR(1) DEFAULT 'N',
  FECHA_ALERTA      TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT fk_alerta_est FOREIGN KEY (ID_ESTUDIANTE) REFERENCES ESTUDIANTE(ID_ESTUDIANTE),
  CONSTRAINT fk_alerta_mat FOREIGN KEY (ID_MATERIA)    REFERENCES MATERIA(ID_MATERIA)
);

